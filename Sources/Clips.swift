import AppKit

/// Riwayat teks yang disalin. Cuma di memori, dan isi yang ditandai rahasia nggak dicatat.
final class ClipHistory: ObservableObject {
    @Published private(set) var items: [String] = []
    private let pasteboard: NSPasteboard
    private let limit = 20
    private var lastCount: Int
    private var timer: Timer?

    /// Standar nspasteboard.org: password manager nandain isinya pakai tipe ini.
    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastCount = pasteboard.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.4
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func poll() {
        guard pasteboard.changeCount != lastCount else { return }
        lastCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secret),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        add(text)
    }

    private func add(_ text: String) {
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastCount = pasteboard.changeCount
        add(text)
    }

    func clear() { items = [] }

    func seed(_ texts: [String]) { items = texts }
}
